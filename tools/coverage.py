"""Generate MITRE ATT&CK coverage artifacts from rule tags.

    python tools/coverage.py           # writes coverage/attack-navigator-layer.json + coverage/COVERAGE.md
    python tools/coverage.py --check   # fail if committed files are out of date

Load the JSON layer at https://mitre-attack.github.io/attack-navigator/
("Open Existing Layer" -> "Upload from local") to see the heatmap.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from detlab.engine import load_rules  # noqa: E402

OUT = ROOT / "coverage"
LAYER = OUT / "attack-navigator-layer.json"
TABLE = OUT / "COVERAGE.md"


def build() -> dict[Path, str]:
    rules = load_rules(ROOT / "rules")
    by_tech: dict[str, list] = defaultdict(list)
    for rule in rules:
        for tech in rule.techniques:
            by_tech[tech].append(rule)

    techniques = []
    for tech in sorted(by_tech):
        titles = sorted(r.title for r in by_tech[tech])
        techniques.append({
            "techniqueID": tech,
            "score": len(titles),
            "comment": "; ".join(titles),
            "enabled": True,
        })

    layer = {
        "name": "Sigma Detection Lab coverage",
        "description": f"{len(rules)} rules covering {len(by_tech)} techniques. Generated by tools/coverage.py.",
        "domain": "enterprise-attack",
        "versions": {"layer": "4.5", "navigator": "5.1.0"},
        "techniques": techniques,
        "gradient": {"colors": ["#c6dbef", "#08519c"], "minValue": 0, "maxValue": 3},
        "legendItems": [],
        "showTacticRowBackground": True,
        "selectSubtechniquesWithParent": False,
        "hideDisabled": False,
    }

    lines = [
        "# ATT&CK Coverage",
        "",
        "_Generated by `tools/coverage.py`. Do not edit by hand._",
        "",
        f"**{len(rules)} rules** covering **{len(by_tech)} techniques**.",
        "",
        "| Technique | Rule | Level | Playbook |",
        "|---|---|---|---|",
    ]
    for tech in sorted(by_tech):
        url = "https://attack.mitre.org/techniques/" + tech.replace(".", "/") + "/"
        for rule in sorted(by_tech[tech], key=lambda r: r.title):
            rel = rule.path.relative_to(ROOT).as_posix()
            lines.append(f"| [{tech}]({url}) | [{rule.title}](../{rel}) | {rule.level} "
                         f"| [triage](../playbooks/{rule.stem}.md) |")

    return {
        LAYER: json.dumps(layer, indent=2) + "\n",
        TABLE: "\n".join(lines) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    files = build()
    if args.check:
        stale = [p for p, t in files.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("Coverage files out of date (run: python tools/coverage.py):",
                  *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
            return 1
        print("coverage files up to date")
        return 0

    OUT.mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {', '.join(str(p.relative_to(ROOT)) for p in files)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
